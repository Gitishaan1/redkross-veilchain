"""Shared fixtures and the test-matrix plugin.

Tests marked with @pytest.mark.tm(id, category, scenario, expected) become rows in
docs/test_matrix.md. Each such test calls `observe("...")` with what actually happened, so the
matrix shows expected versus OBSERVED behaviour from a real run, not hand-written claims.
Generate it with:  pytest --write-matrix docs/test_matrix.md
"""

from __future__ import annotations

import contextlib
import io
from pathlib import Path

import pytest

from veilchain.cli import main
from veilchain.keys import DEMO_KEY, KeyRing

ROOT = Path(__file__).resolve().parents[1]
POLICY = str(ROOT / "policy" / "data_classification_policy.json")
RULES = str(ROOT / "policy" / "veilchain_rules.json")
RECORDS = ROOT / "data" / "customer_records_synthetic.csv"
CASES = ROOT / "data" / "redaction_test_cases.csv"

_MATRIX: list[dict] = []
_OBSERVED: dict[str, list[str]] = {}


def pytest_addoption(parser):
    parser.addoption("--write-matrix", default=None, help="write the test matrix (markdown) to this path")


@pytest.fixture
def policy_path():
    return POLICY


@pytest.fixture
def rules_path():
    return RULES


@pytest.fixture
def records():
    return RECORDS


@pytest.fixture
def cases():
    return CASES


@pytest.fixture
def demo_keyring():
    return KeyRing(DEMO_KEY, "demo")


@pytest.fixture
def observe(request):
    def _observe(text: str) -> None:
        _OBSERVED.setdefault(request.node.nodeid, []).append(text)
    return _observe


@pytest.fixture
def cli():
    """Run the CLI in-process. Returns (exit_code, stdout, stderr)."""
    def _run(*argv: str):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                code = main(list(argv))
            except SystemExit as exc:  # argparse errors
                code = exc.code if isinstance(exc.code, int) else 3
        return code, out.getvalue(), err.getvalue()
    return _run


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    report = outcome.get_result()
    if report.when != "call":
        if report.when == "setup" and report.outcome == "failed":
            pass
        return
    marker = item.get_closest_marker("tm")
    if marker:
        tm_id, category, scenario, expected = marker.args
        _MATRIX.append({
            "id": tm_id, "category": category, "scenario": scenario, "expected": expected,
            "observed": "; ".join(_OBSERVED.get(item.nodeid, [])) or "(no observation recorded)",
            "result": "PASS" if report.passed else "FAIL",
        })


def pytest_sessionfinish(session, exitstatus):
    path = session.config.getoption("--write-matrix")
    if not path or not _MATRIX:
        return
    rows = sorted(_MATRIX, key=lambda r: r["id"])
    passed = sum(1 for r in rows if r["result"] == "PASS")
    lines = [
        "# Test matrix",
        "",
        f"Generated by `pytest --write-matrix`. {len(rows)} matrix cases: {passed} passed, {len(rows) - passed} failed.",
        "The *Observed* column is recorded by the test while it runs, so it shows what really happened.",
        "",
        "| ID | Category | Scenario | Expected | Observed | Result |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        cells = [r["id"], r["category"], r["scenario"], r["expected"], r["observed"].replace("|", "/"), r["result"]]
        lines.append("| " + " | ".join(c.replace("\n", " ") for c in cells) + " |")
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
